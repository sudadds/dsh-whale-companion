const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('overlay', {
  moveBy: (dx, dy) => ipcRenderer.send('move-by', dx, dy),
  dragStart: () => ipcRenderer.send('drag-start'),
  dragEnd: () => ipcRenderer.send('drag-end'),
  demoSay: () => ipcRenderer.send('demo-say'),
  cycleIcon: () => ipcRenderer.send('cycle-icon'),
  prepareBubble: (size) => ipcRenderer.send('prepare-bubble', size),
  bubbleClosed: () => ipcRenderer.send('bubble-closed'),
  trace: (name, data) => ipcRenderer.send('trace', name, data),
  chatSend: (text) => ipcRenderer.send('chat-send', text),
  syncSize: (size) => ipcRenderer.send('sync-size', size),
  inputState: (open) => ipcRenderer.send('input-state', open),
  capture: () => ipcRenderer.send('capture'),
  getInfo: () => ipcRenderer.invoke('get-info'),
  settingsStatus: () => ipcRenderer.invoke('settings-status'),
  watchSet: (opts) => ipcRenderer.send('watch-set', opts),
  speedSet: (name) => ipcRenderer.send('speed-set', name),
  opacitySet: (v) => ipcRenderer.send('opacity-set', v),
  panelState: (open) => ipcRenderer.send('panel-state', open),
  personaGet: () => ipcRenderer.invoke('persona-get'),
  personaSave: (text) => ipcRenderer.send('persona-save', text),
  onSay: (fn) => ipcRenderer.on('say', (_e, v) => fn(v)),
  onConfig: (fn) => ipcRenderer.on('config', (_e, v) => fn(v)),
  onIcon: (fn) => ipcRenderer.on('icon', (_e, v) => fn(v)),
  onSettings: (fn) => ipcRenderer.on('settings', (_e, v) => fn(v)),
  onSpeedChanged: (fn) => ipcRenderer.on('speed-changed', (_e, v) => fn(v)),
  onOpacity: (fn) => ipcRenderer.on('opacity', (_e, v) => fn(v)),
  onLayout: (fn) => ipcRenderer.on('layout', (_e, v) => fn(v)),
  onHideBubble: (fn) => ipcRenderer.on('hide-bubble', () => fn()),
  onCapture: (fn) => ipcRenderer.on('capture-request', () => fn()),
  onInteractive: (fn) => ipcRenderer.on('interactive', (_e, v) => fn(v)),
  onHotkey: (fn) => ipcRenderer.on('hotkey-flash', () => fn()),
})
